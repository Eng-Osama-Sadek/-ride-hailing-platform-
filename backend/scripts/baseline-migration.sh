#!/bin/sh
# ينشئ migration أولية من schema.prisma ويسجّلها كمُطبَّقة على قاعدة التطوير الحالية.
# نفّذها مرة واحدة ثم ارفع مجلد prisma/migrations إلى Git.
set -e
if [ -d prisma/migrations ] && [ -n "$(ls -A prisma/migrations 2>/dev/null)" ]; then
  echo "Migrations already exist — nothing to do."; exit 0
fi
mkdir -p prisma/migrations/0001_init
npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > prisma/migrations/0001_init/migration.sql
printf '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n' > prisma/migrations/migration_lock.toml
npx prisma migrate resolve --applied 0001_init
echo "✅ Baseline migration created: prisma/migrations/0001_init"
